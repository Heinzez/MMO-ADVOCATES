export function getSyntheticDashboardData(): DashboardData {
    const today = getNairobiDateString(0);
    const todayItems = SYNTHETIC_FOLLOW_UPS.filter(
        (f) => f.status === 'pending' && f.due_on === today
    );
    const overdueItems = SYNTHETIC_FOLLOW_UPS.filter(
        (f) => f.status === 'pending' && f.due_on < today
    );

    return {
        date: today,
        timezone: 'Africa/Nairobi',
        today: todayItems,
        overdue: overdueItems,
    };
}
