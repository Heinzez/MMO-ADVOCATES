// Compute Africa/Nairobi dates (UTC+3)
export function getNairobiDateString(offsetDays = 0): string {
    const now = new Date();
    // UTC+3 offset
    const nairobiTime = new Date(now.getTime() + (3 * 60 + now.getTimezoneOffset()) * 60000);
    nairobiTime.setDate(nairobiTime.getDate() + offsetDays);
    return nairobiTime.toISOString().split('T')[0];
}

